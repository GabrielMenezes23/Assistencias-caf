create or replace function private.normalize_text(input text)
returns text
language sql
stable
set search_path = ''
as $$
  select trim(regexp_replace(upper(extensions.unaccent(coalesce(input, ''))), '[^A-Z0-9]+', ' ', 'g'));
$$;

revoke all on function private.normalize_text(text) from public;
grant execute on function private.normalize_text(text) to authenticated;

create or replace function private.is_active_user()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and ativo
  );
$$;

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and ativo and perfil = 'administrador'
  );
$$;

revoke all on function private.is_active_user() from public;
revoke all on function private.is_admin() from public;
grant execute on function private.is_active_user() to authenticated;
grant execute on function private.is_admin() to authenticated;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, nome)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), nullif(split_part(new.email, '@', 1), ''), 'Usuário')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;
revoke all on function private.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

