create or replace function public.search_municipalities(p_query text, p_limit integer default 8)
returns table (
  ibge text,
  nome text,
  uf char(2),
  latitude double precision,
  longitude double precision,
  relevance real
)
language sql
stable
security invoker
set search_path = ''
as $$
  with normalized as (
    select private.normalize_text(p_query) as value
  )
  select
    m.ibge,
    m.nome,
    m.uf,
    m.latitude,
    m.longitude,
    greatest(
      extensions.similarity(m.nome_normalizado, n.value),
      case when m.nome_normalizado = n.value then 1 else 0 end
    )::real as relevance
  from public.municipios m
  cross join normalized n
  where private.is_active_user()
    and (
      m.nome_normalizado operator(extensions.%) n.value
      or m.nome_normalizado like n.value || '%'
      or n.value like m.nome_normalizado || '%'
    )
  order by relevance desc, m.nome, m.uf
  limit greatest(1, least(coalesce(p_limit, 8), 20));
$$;

create or replace function public.search_nearby_assistances(
  p_lat double precision,
  p_lng double precision,
  p_limit integer default 8,
  p_include_blocked boolean default false
)
returns table (
  id bigint,
  title text,
  city text,
  uf char(2),
  distance_km double precision,
  score_km double precision,
  status public.assistance_status,
  alert text,
  phones jsonb,
  emails jsonb,
  cnpjs jsonb,
  ceps jsonb,
  addresses jsonb,
  latitude double precision,
  longitude double precision,
  geo_source public.geo_source_kind,
  location_label text,
  distance_is_approximate boolean,
  blocked_count bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  with origin as (
    select extensions.st_setsrid(extensions.st_makepoint(p_lng, p_lat), 4326)::extensions.geography as point
  ),
  distances as (
    select
      a.*,
      extensions.st_distance(a.location, o.point) / 1000.0 as raw_distance_km
    from public.assistencias a
    cross join origin o
    where private.is_active_user() and a.ativo
  ),
  allowed as (
    select *
    from distances
    where p_include_blocked or status <> 'NAO_INDICAR'
  ),
  nearest_allowed as (
    select min(raw_distance_km) as km
    from distances
    where status <> 'NAO_INDICAR'
  ),
  blocked as (
    select count(*)::bigint as total
    from distances d
    cross join nearest_allowed n
    where d.status = 'NAO_INDICAR'
      and d.raw_distance_km <= coalesce(n.km + 100.0, 200.0)
  )
  select
    a.id,
    a.titulo as title,
    a.cidade as city,
    a.uf,
    round(a.raw_distance_km::numeric, 1)::double precision as distance_km,
    a.raw_distance_km as score_km,
    a.status,
    a.alerta as alert,
    a.telefones as phones,
    a.emails,
    a.cnpjs,
    a.ceps,
    a.enderecos as addresses,
    a.effective_latitude as latitude,
    a.effective_longitude as longitude,
    a.geo_source,
    a.geo_label as location_label,
    a.geo_source = 'municipality' as distance_is_approximate,
    b.total as blocked_count
  from allowed a
  cross join blocked b
  order by score_km, distance_km, title
  limit greatest(1, least(coalesce(p_limit, 8), 20));
$$;


create or replace function public.apply_assistance_import(p_importacao_id uuid)
returns table (created_count integer, updated_count integer)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_import public.importacoes%rowtype;
  v_line record;
  v_data jsonb;
  v_municipality jsonb;
  v_address text;
  v_content text;
  v_created integer := 0;
  v_updated integer := 0;
  v_lat double precision;
  v_lng double precision;
begin
  if not private.is_admin() then
    raise exception 'Apenas administradores podem aplicar importações.';
  end if;

  select * into v_import
  from public.importacoes
  where id = p_importacao_id
  for update;

  if not found then
    raise exception 'Importação não encontrada.';
  end if;
  if v_import.status = 'CONCLUIDO' then
    raise exception 'Esta importação já foi aplicada.';
  end if;
  if v_import.erros > 0 then
    raise exception 'A importação possui linhas com erro.';
  end if;

  update public.importacoes set status = 'PROCESSANDO' where id = p_importacao_id;

  for v_line in
    select acao_proposta, assistencia_id, dados_normalizados
    from public.importacao_linhas
    where importacao_id = p_importacao_id
      and acao_proposta in ('CRIAR', 'ATUALIZAR')
    order by numero_linha
  loop
    v_data := v_line.dados_normalizados -> 'data';
    v_municipality := v_line.dados_normalizados -> 'municipality';
    if v_data is null or v_municipality is null then
      raise exception 'Linha validada sem dados normalizados.';
    end if;
    v_lat := nullif(v_data ->> 'latitude', '')::double precision;
    v_lng := nullif(v_data ->> 'longitude', '')::double precision;
    v_address := concat_ws(', ',
      nullif(v_data ->> 'address', ''),
      nullif(v_data ->> 'neighborhood', '')
    );
    v_content := concat_ws(E'\n\n',
      concat(v_data ->> 'city', '/', v_data ->> 'uf'),
      v_data ->> 'title',
      case when jsonb_array_length(coalesce(v_data -> 'cnpjs', '[]'::jsonb)) > 0 then 'CNPJ: ' || array_to_string(array(select jsonb_array_elements_text(v_data -> 'cnpjs')), ' / ') end,
      nullif(v_address, ''),
      case when nullif(v_data ->> 'cep', '') is not null then 'CEP: ' || (v_data ->> 'cep') end,
      case when jsonb_array_length(coalesce(v_data -> 'phones', '[]'::jsonb)) > 0 then array_to_string(array(select jsonb_array_elements_text(v_data -> 'phones')), ' / ') end,
      case when jsonb_array_length(coalesce(v_data -> 'emails', '[]'::jsonb)) > 0 then array_to_string(array(select jsonb_array_elements_text(v_data -> 'emails')), ' / ') end,
      nullif(v_data ->> 'notes', '')
    );

    if v_line.acao_proposta = 'CRIAR' then
      insert into public.assistencias (
        municipio_ibge, cidade, cidade_normalizada, uf, titulo, cabecalho, conteudo_original,
        status, alerta, endereco, bairro, cep_principal, observacoes, telefones, emails, cnpjs, ceps, enderecos,
        latitude_municipio, longitude_municipio, geo_latitude, geo_longitude,
        geo_source, geo_label, ativo
      ) values (
        v_municipality ->> 'ibge', v_data ->> 'city', private.normalize_text(v_data ->> 'city'), v_data ->> 'uf',
        v_data ->> 'title', concat(v_data ->> 'city', '/', v_data ->> 'uf'), v_content,
        coalesce(v_data ->> 'status', 'NORMAL')::public.assistance_status, coalesce(v_data ->> 'alert', ''),
        coalesce(v_data ->> 'address', ''), coalesce(v_data ->> 'neighborhood', ''), coalesce(v_data ->> 'cep', ''), coalesce(v_data ->> 'notes', ''),
        coalesce(v_data -> 'phones', '[]'::jsonb), coalesce(v_data -> 'emails', '[]'::jsonb), coalesce(v_data -> 'cnpjs', '[]'::jsonb),
        case when nullif(v_data ->> 'cep', '') is null then '[]'::jsonb else jsonb_build_array(v_data ->> 'cep') end,
        case when nullif(v_address, '') is null then '[]'::jsonb else jsonb_build_array(v_address) end,
        (v_municipality ->> 'latitude')::double precision, (v_municipality ->> 'longitude')::double precision,
        v_lat, v_lng, (case when v_lat is null then 'municipality' else 'manual' end)::public.geo_source_kind,
        case when v_lat is null then concat(v_municipality ->> 'nome', '/', v_municipality ->> 'uf') else concat_ws(', ', nullif(v_address, ''), concat(v_data ->> 'city', '/', v_data ->> 'uf')) end,
        coalesce((v_data ->> 'active')::boolean, true)
      );
      v_created := v_created + 1;
    else
      update public.assistencias set
        municipio_ibge = v_municipality ->> 'ibge',
        cidade = v_data ->> 'city', cidade_normalizada = private.normalize_text(v_data ->> 'city'), uf = v_data ->> 'uf',
        titulo = v_data ->> 'title', cabecalho = concat(v_data ->> 'city', '/', v_data ->> 'uf'), conteudo_original = v_content,
        status = coalesce(v_data ->> 'status', 'NORMAL')::public.assistance_status, alerta = coalesce(v_data ->> 'alert', ''),
        endereco = coalesce(v_data ->> 'address', ''), bairro = coalesce(v_data ->> 'neighborhood', ''),
        cep_principal = coalesce(v_data ->> 'cep', ''), observacoes = coalesce(v_data ->> 'notes', ''),
        telefones = coalesce(v_data -> 'phones', '[]'::jsonb), emails = coalesce(v_data -> 'emails', '[]'::jsonb), cnpjs = coalesce(v_data -> 'cnpjs', '[]'::jsonb),
        ceps = case when nullif(v_data ->> 'cep', '') is null then '[]'::jsonb else jsonb_build_array(v_data ->> 'cep') end,
        enderecos = case when nullif(v_address, '') is null then '[]'::jsonb else jsonb_build_array(v_address) end,
        latitude_municipio = (v_municipality ->> 'latitude')::double precision,
        longitude_municipio = (v_municipality ->> 'longitude')::double precision,
        geo_latitude = v_lat, geo_longitude = v_lng,
        geo_source = (case when v_lat is null then 'municipality' else 'manual' end)::public.geo_source_kind,
        geo_label = case when v_lat is null then concat(v_municipality ->> 'nome', '/', v_municipality ->> 'uf') else concat_ws(', ', nullif(v_address, ''), concat(v_data ->> 'city', '/', v_data ->> 'uf')) end,
        ativo = coalesce((v_data ->> 'active')::boolean, true)
      where id = v_line.assistencia_id;
      if not found then
        raise exception 'Assistência de atualização não encontrada: %', v_line.assistencia_id;
      end if;
      v_updated := v_updated + 1;
    end if;
  end loop;

  update public.importacoes
  set status = 'CONCLUIDO', finished_at = now()
