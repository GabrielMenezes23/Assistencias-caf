create or replace function private.stamp_assistance_user()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.created_by = coalesce(new.created_by, (select auth.uid()));
  else
    new.created_by = old.created_by;
  end if;
  new.updated_by = coalesce((select auth.uid()), new.updated_by);
  return new;
end;
$$;
revoke all on function private.stamp_assistance_user() from public, anon, authenticated;

create trigger assistencias_stamp_user
before insert or update on public.assistencias
for each row execute function private.stamp_assistance_user();

create or replace function private.log_assistance_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  action_value public.audit_action;
begin
  if tg_op = 'INSERT' then
    action_value := 'INSERT';
  elsif tg_op = 'DELETE' then
    action_value := 'DELETE';
  elsif old.ativo and not new.ativo then
    action_value := 'DEACTIVATE';
  elsif not old.ativo and new.ativo then
    action_value := 'ACTIVATE';
  else
    action_value := 'UPDATE';
  end if;

  insert into public.assistencia_audit_log (
    assistencia_id, acao, dados_anteriores, dados_novos, changed_by
  ) values (
    coalesce(new.id, old.id),
    action_value,
    case when tg_op = 'INSERT' then null else to_jsonb(old) - 'location' end,
    case when tg_op = 'DELETE' then null else to_jsonb(new) - 'location' end,
    (select auth.uid())
  );
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;
revoke all on function private.log_assistance_change() from public, anon, authenticated;

create trigger assistencias_audit
after insert or update or delete on public.assistencias
for each row execute function private.log_assistance_change();

