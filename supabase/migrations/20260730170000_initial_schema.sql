-- CAF Assistência Web — schema inicial seguro e geográfico.
-- Aplicar em um projeto Supabase novo antes de importar os CSVs de supabase/seed.

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

create extension if not exists pgcrypto with schema extensions;
create extension if not exists postgis with schema extensions;
create extension if not exists unaccent with schema extensions;
create extension if not exists pg_trgm with schema extensions;

create type public.profile_role as enum ('usuario', 'administrador');
create type public.assistance_status as enum ('NORMAL', 'CONSULTAR_ANTES', 'NAO_INDICAR');
create type public.geo_source_kind as enum ('municipality', 'cep', 'address', 'manual');
create type public.import_status as enum ('ENVIADO', 'VALIDADO', 'PROCESSANDO', 'CONCLUIDO', 'FALHOU', 'CANCELADO');
create type public.import_row_action as enum ('CRIAR', 'ATUALIZAR', 'IGNORAR_DUPLICADO', 'ERRO');
create type public.audit_action as enum ('INSERT', 'UPDATE', 'DELETE', 'ACTIVATE', 'DEACTIVATE');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null check (char_length(trim(nome)) between 1 and 160),
  perfil public.profile_role not null default 'usuario',
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.municipios (
  ibge text primary key,
  nome text not null,
  nome_normalizado text not null,
  uf char(2) not null check (uf ~ '^[A-Z]{2}$'),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  location extensions.geography(Point, 4326)
    generated always as (
      extensions.st_setsrid(extensions.st_makepoint(longitude, latitude), 4326)::extensions.geography
    ) stored
);

create table public.assistencias (
  id bigint generated by default as identity primary key,
  legacy_id integer unique,
  municipio_ibge text not null references public.municipios(ibge),
  cidade text not null,
  cidade_normalizada text not null,
  uf char(2) not null check (uf ~ '^[A-Z]{2}$'),
  titulo text not null check (char_length(trim(titulo)) between 1 and 240),
  cabecalho text not null default '',
  conteudo_original text not null default '',
  status public.assistance_status not null default 'NORMAL',
  alerta text not null default '',
  endereco text not null default '',
  bairro text not null default '',
  cep_principal text not null default '',
  observacoes text not null default '',
  telefones jsonb not null default '[]'::jsonb check (jsonb_typeof(telefones) = 'array'),
  emails jsonb not null default '[]'::jsonb check (jsonb_typeof(emails) = 'array'),
  cnpjs jsonb not null default '[]'::jsonb check (jsonb_typeof(cnpjs) = 'array'),
  ceps jsonb not null default '[]'::jsonb check (jsonb_typeof(ceps) = 'array'),
  enderecos jsonb not null default '[]'::jsonb check (jsonb_typeof(enderecos) = 'array'),
  latitude_municipio double precision not null check (latitude_municipio between -90 and 90),
  longitude_municipio double precision not null check (longitude_municipio between -180 and 180),
  geo_latitude double precision check (geo_latitude between -90 and 90),
  geo_longitude double precision check (geo_longitude between -180 and 180),
  geo_source public.geo_source_kind not null default 'municipality',
  geo_label text not null default '',
  effective_latitude double precision
    generated always as (coalesce(geo_latitude, latitude_municipio)) stored,
  effective_longitude double precision
    generated always as (coalesce(geo_longitude, longitude_municipio)) stored,
  location extensions.geography(Point, 4326)
    generated always as (
      extensions.st_setsrid(
        extensions.st_makepoint(
          coalesce(geo_longitude, longitude_municipio),
          coalesce(geo_latitude, latitude_municipio)
        ),
        4326
      )::extensions.geography
    ) stored,
  ativo boolean not null default true,
  created_by uuid references public.profiles(id),
  updated_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((geo_latitude is null and geo_longitude is null) or (geo_latitude is not null and geo_longitude is not null))
);

create table public.geocode_cache (
  cache_key text primary key,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  label text not null,
  source text not null,
  precision text not null,
  updated_at timestamptz not null default now()
);

create table public.importacoes (
  id uuid primary key default extensions.gen_random_uuid(),
  arquivo_nome text not null,
  storage_path text,
  status public.import_status not null default 'ENVIADO',
  total_linhas integer not null default 0 check (total_linhas >= 0),
  novos integer not null default 0 check (novos >= 0),
  atualizados integer not null default 0 check (atualizados >= 0),
  ignorados integer not null default 0 check (ignorados >= 0),
  erros integer not null default 0 check (erros >= 0),
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  finished_at timestamptz
);

create table public.importacao_linhas (
  id bigint generated by default as identity primary key,
  importacao_id uuid not null references public.importacoes(id) on delete cascade,
  numero_linha integer not null check (numero_linha >= 2),
  dados_originais jsonb not null,
  dados_normalizados jsonb,
  acao_proposta public.import_row_action not null,
  assistencia_id bigint references public.assistencias(id),
  erros jsonb not null default '[]'::jsonb check (jsonb_typeof(erros) = 'array'),
  avisos jsonb not null default '[]'::jsonb check (jsonb_typeof(avisos) = 'array'),
  unique(importacao_id, numero_linha)
);

create table public.assistencia_audit_log (
  id bigint generated by default as identity primary key,
  assistencia_id bigint,
  acao public.audit_action not null,
  dados_anteriores jsonb,
  dados_novos jsonb,
  changed_by uuid references public.profiles(id),
  changed_at timestamptz not null default now()
);

