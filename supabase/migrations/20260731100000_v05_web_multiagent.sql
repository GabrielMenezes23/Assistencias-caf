for delete to authenticated using (
  exists (select 1 from public.agent_conversations c where c.id = conversation_id and c.user_id = (select auth.uid()))
);

create or replace function private.touch_conversation_from_message()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  update public.agent_conversations
  set updated_at = now()
  where id = new.conversation_id;
  return new;
end;
$$;
revoke all on function private.touch_conversation_from_message() from public, anon, authenticated;
drop trigger if exists agent_messages_touch_conversation on public.agent_messages;
create trigger agent_messages_touch_conversation
after insert on public.agent_messages
for each row execute function private.touch_conversation_from_message();

