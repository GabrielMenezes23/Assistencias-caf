create or replace function private.has_profile_role(allowed_roles public.profile_role[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and ativo
      and perfil = any(allowed_roles)
  );
$$;
revoke all on function private.has_profile_role(public.profile_role[]) from public, anon;
grant execute on function private.has_profile_role(public.profile_role[]) to authenticated;

create or replace function private.is_reviewer_or_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select private.has_profile_role(array['revisor', 'administrador']::public.profile_role[]);
$$;
revoke all on function private.is_reviewer_or_admin() from public, anon;
grant execute on function private.is_reviewer_or_admin() to authenticated;

-- O texto importado é uma evidência histórica. Edições posteriores alteram somente campos estruturados.
create or replace function private.preserve_assistance_source_snapshot()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.legacy_id := old.legacy_id;
  new.cabecalho := old.cabecalho;
  new.conteudo_original := old.conteudo_original;
  new.fonte_hash := old.fonte_hash;
  new.fonte_importada_em := old.fonte_importada_em;
  return new;
end;
$$;
revoke all on function private.preserve_assistance_source_snapshot() from public, anon, authenticated;

drop trigger if exists assistencias_preserve_source on public.assistencias;
create trigger assistencias_preserve_source
before update on public.assistencias
for each row execute function private.preserve_assistance_source_snapshot();

-- Conversas determinísticas dos agentes. Nenhum conteúdo depende de IA.
create table if not exists public.agent_conversations (
  id uuid primary key default extensions.gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  agent_id text not null check (agent_id in ('assistencias', 'vendas')),
  titulo text not null default 'Nova conversa',
  state jsonb not null default '{}'::jsonb check (jsonb_typeof(state) = 'object'),
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.agent_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.agent_conversations(id) on delete cascade,
  role text not null check (role in ('operator', 'assistant', 'system')),
  content text not null,
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  created_at timestamptz not null default now()
);

create index if not exists agent_conversations_user_idx
  on public.agent_conversations(user_id, updated_at desc)
  where not archived;
create index if not exists agent_messages_conversation_idx
  on public.agent_messages(conversation_id, created_at, id);

alter table public.agent_conversations enable row level security;
alter table public.agent_messages enable row level security;

