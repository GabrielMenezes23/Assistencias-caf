  double precision,
  double precision,
  integer,
  boolean
);

create or replace function public.search_nearby_assistances(
  p_lat double precision,
  p_lng double precision,
  p_limit integer default 8,
  p_include_blocked boolean default false
)
returns table (
  id bigint,
  title text,
  city text,
  uf char(2),
  distance_km double precision,
  score_km double precision,
  status public.assistance_status,
  alert text,
  restrictions jsonb,
  displacement boolean,
  warranty boolean,
  invoice boolean,
  phones jsonb,
  emails jsonb,
  cnpjs jsonb,
  ceps jsonb,
  addresses jsonb,
  latitude double precision,
  longitude double precision,
  geo_source public.geo_source_kind,
  location_label text,
  distance_is_approximate boolean,
  ranking_group text,
  distance_method text,
  distance_label text,
  distance_band text,
  same_distance_group boolean,
  route_allowed boolean,
  blocked_count bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  with origin as (
    select extensions.st_setsrid(extensions.st_makepoint(p_lng, p_lat), 4326)::extensions.geography as point
  ),
  distances as (
    select
      a.*,
      extensions.st_distance(a.location, o.point) / 1000.0 as raw_distance_km
    from public.assistencias a
    cross join origin o
    where private.is_active_user() and a.ativo
  ),
  blocked as (
    select count(*)::bigint as total
    from distances
    where status = 'NAO_INDICAR'
  ),
  allowed as (
    select
      d.*,
      case when d.status = 'CONSULTAR_ANTES' then 'consult_before' else 'recommended' end as group_name,
      case when d.status = 'CONSULTAR_ANTES' then 1 else 0 end as group_priority,
      case
        when d.geo_source = 'municipality' then concat('municipality:', round(d.raw_distance_km::numeric, 1))
        else concat('precise:', d.id, ':', round(d.raw_distance_km::numeric, 1))
      end as band
    from distances d
    where p_include_blocked or d.status <> 'NAO_INDICAR'
  ),
  selected as (
    select *
    from allowed
    order by group_priority, raw_distance_km, titulo
    limit greatest(1, least(coalesce(p_limit, 8), 20))
  ),
  marked as (
    select s.*, count(*) over (partition by s.band) > 1 as tied
    from selected s
  )
  select
    a.id,
    a.titulo as title,
    a.cidade as city,
    a.uf,
    round(a.raw_distance_km::numeric, 1)::double precision as distance_km,
    a.raw_distance_km as score_km,
    a.status,
    a.alerta as alert,
    a.restricoes as restrictions,
    a.faz_deslocamento as displacement,
    a.atende_garantia as warranty,
    a.emite_nota as invoice,
    a.telefones as phones,
    a.emails,
    a.cnpjs,
    a.ceps,
    a.enderecos as addresses,
    a.effective_latitude as latitude,
    a.effective_longitude as longitude,
    a.geo_source,
    a.geo_label as location_label,
    a.geo_source = 'municipality' as distance_is_approximate,
    a.group_name as ranking_group,
    'haversine'::text as distance_method,
    case
      when a.geo_source = 'municipality' and a.raw_distance_km < 0.1 then 'Mesmo município — ordem interna não determinada'
      when a.geo_source = 'municipality' then 'Distância aproximada entre municípios'
      else 'Distância em linha reta por endereço/coordenada'
    end as distance_label,
    a.band as distance_band,
    a.tied as same_distance_group,
    a.geo_source <> 'municipality' as route_allowed,
    b.total as blocked_count
  from marked a
  cross join blocked b
  order by a.group_priority, a.raw_distance_km, a.titulo;
$$;

revoke all on function public.search_nearby_assistances(double precision, double precision, integer, boolean) from public, anon;
grant execute on function public.search_nearby_assistances(double precision, double precision, integer, boolean) to authenticated;

